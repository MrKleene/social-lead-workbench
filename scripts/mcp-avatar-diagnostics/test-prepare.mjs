import assert from 'node:assert/strict';
import {mkdtemp,readFile,writeFile,mkdir,symlink} from 'node:fs/promises';
import {join,dirname,resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const bundle=dirname(fileURLToPath(import.meta.url)),source=resolve(process.argv[2]);
const root=await mkdtemp(join(tmpdir(),'mcp-avatar-prepare-'));
const run=(src,dest)=>spawnSync(process.execPath,[join(bundle,'prepare.mjs'),src,dest],{encoding:'utf8',env:{PATH:'/usr/bin:/bin'},timeout:15000});
const target=join(root,'candidate');assert.equal(run(source,target).status,0);
assert.match(await readFile(join(target,'xiaohongshu/feed_detail.go'),'utf8'),/inspectRawAvatarSource/);
assert.match(await readFile(join(target,'xiaohongshu/types.go'),'utf8'),/avatarSourceDiagnostic/);
assert.notEqual(run(source,target).status,0,'must not overwrite candidate');
assert.notEqual(run(source,join(source,'unauthorized-child')).status,0,'must not edit original tree');
assert.notEqual(run(target,join(root,'changed-source')).status,0,'must reject patched/drifted source');
const unsafe=join(root,'unsafe');await mkdir(unsafe);
const manifest=JSON.parse(await readFile(join(bundle,'source-manifest.json'),'utf8'));
const first=Object.keys(manifest.files)[0];await mkdir(dirname(join(unsafe,first)),{recursive:true});await symlink(join(source,first),join(unsafe,first));
assert.notEqual(run(unsafe,join(root,'symlink-output')).status,0,'must reject source symlink');
console.log('5 preparation checks passed; no MCP binary executed');
